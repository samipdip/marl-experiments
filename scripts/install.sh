#!/usr/bin/env bash
# scripts/install.sh — Install or update the FastBoxEx SDK and client binaries.
#
# Usage:
#   bash scripts/install.sh              # on-campus (default)
#   bash scripts/install.sh --off-campus # off-campus via SSH tunnel

set -e

CAMPUS_HOST="172.16.210.57"
TUNNEL_HOST="127.0.0.1"

# ── Resolve download base and default profile ─────────────────────────────────
OFF_CAMPUS=false
if [ "${1:-}" = "--off-campus" ]; then
    OFF_CAMPUS=true
fi

if $OFF_CAMPUS; then
    BASE="http://${TUNNEL_HOST}:8880"
    echo "Mode: off-campus (SSH tunnel to ${TUNNEL_HOST}:8880)"
else
    BASE="http://${CAMPUS_HOST}:8880"
    echo "Mode: on-campus (${CAMPUS_HOST}:8880)"
fi

# ── Python venv ───────────────────────────────────────────────────────────────
if [ ! -d ".venv" ]; then
    echo "Creating Python 3.13 virtualenv..."
    uv venv --python 3.13 .venv
fi

echo "Activating virtualenv..."
# shellcheck disable=SC1091
source .venv/bin/activate

# ── SDK wheel ─────────────────────────────────────────────────────────────────
echo "Fetching SDK version from server..."
WHEEL=$(curl -sf "${BASE}/wheels/fastboxex-version.txt")
if [ -z "$WHEEL" ]; then
    echo "✗ Could not fetch version from ${BASE}/wheels/fastboxex-version.txt"
    if $OFF_CAMPUS; then
        echo "  Is the SSH tunnel open?"
    else
        echo "  Are you on campus? Try: bash scripts/install.sh --off-campus"
    fi
    exit 1
fi

echo "Installing ${WHEEL}..."
wget -q --show-progress -P /tmp "${BASE}/wheels/${WHEEL}"
uv pip install "/tmp/${WHEEL}"
rm -f "/tmp/${WHEEL}"

# ── SDK Python dependencies ───────────────────────────────────────────────────
echo "Installing SDK dependencies..."
uv pip install "numpy>=1.20" "polars>=0.20"

# ── Client TUI binary ─────────────────────────────────────────────────────────
echo "Downloading fastboxex-tui..."
wget -q --show-progress -O fastboxex-tui "${BASE}/wheels/fastboxex-client-tui-latest"
chmod +x fastboxex-tui

# ── Config.toml ───────────────────────────────────────────────────────────────
if [ -f Config.toml ]; then
    echo "  Config.toml already exists — skipping generation."
else
    echo "Generating Config.toml..."
    # On-campus install puts campus profile first (= default).
    # Off-campus install puts tunnel profile first (= default).
    if $OFF_CAMPUS; then
        FIRST_NAME="Off-campus (SSH tunnel)"
        FIRST_HOST="${TUNNEL_HOST}"
        SECOND_NAME="On-campus"
        SECOND_HOST="${CAMPUS_HOST}"
    else
        FIRST_NAME="On-campus"
        FIRST_HOST="${CAMPUS_HOST}"
        SECOND_NAME="Off-campus (SSH tunnel)"
        SECOND_HOST="${TUNNEL_HOST}"
    fi

    cat > Config.toml << EOF
# FastBoxEx client configuration — auto-generated by install.sh
# Add your username below. Password via env var only (never in this file).
#   export FASTBOXEX_PASSWORD="yourpassword"
#
# All service endpoints are DERIVED from the active profile's host:
#   auth       tcp://<host>:11001    relay     tcp://<host>:11050
#   arena      tcp://<host>:11003    log_pub   tcp://<host>:11004
#   arena_pub  tcp://<host>:11051    fill_pub  tcp://<host>:11005
#   arena_rtr  tcp://<host>:11052    dashboard http://<host>:8880
#
# Profile selection (pick one method):
#   1. The FIRST profile below is used by default.
#   2. FASTBOXEX_PROFILE="on-campus" python script.py   (env var)
#   3. cfg = load(profile="on-campus")                  (in-script)

[connection]
username = ""   # <- set your username here

[[connection.profiles]]
name = "${FIRST_NAME}"
host = "${FIRST_HOST}"

[[connection.profiles]]
name = "${SECOND_NAME}"
host = "${SECOND_HOST}"

[storage]
runs_dir = "runs"

[logging]
level = "info"
EOF
    echo "  ✓ Config.toml created (default profile: ${FIRST_NAME})."
fi

echo ""
echo "✓ Done! SDK ${WHEEL} installed."
echo ""
echo "  Next: edit Config.toml → set username"
echo "        export FASTBOXEX_PASSWORD=\"yourpassword\""
echo ""
echo "  Dashboard : ${BASE}/"
echo "  Docs      : ${BASE}/docs/"
echo "  TUI       : ./fastboxex-tui"
